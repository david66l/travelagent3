"""Migration must not invent facts, import labels or escape the offline registry."""
import json
import pytest
from evaluation.migration_fixture import MigrationResearchExecutor, rebuild_case


def source_case():
    poi = {"id": "p1", "name": "冻结展馆", "category": "attraction", "location": {"lat": 31.2, "lng": 121.4}, "open_time": "09:00", "close_time": "17:00", "recommended_hours": 2, "ticket_price": 30}
    slots = {"destination": "上海", "travel_days": 1, "budget_range": 300}
    return {"id": "migration-test", "request": {"request": "上海玩一天，预算300元", "hard_constraints": slots},
            "audit": {"group": {"source_group": "source-one"}}, "source": {
                "task": {"user_request": "上海玩一天，预算300元", "template_family": "plain", "slots": slots, "profile": {}, "missing_slots": []},
                "snapshot": {"hidden_test_facts": {"target_action": "abort", "secret_marker": "NEVER_IN_PROMPT"}, "tool_responses": {
                    "search_pois": [{"data": [poi], "expected_arguments": {"keywords": ["展馆"]}}],
                    "solve_itinerary": [{"data": {"oracle": "NEVER_IN_PROMPT"}}],
                    "validate_itinerary": [{"data": {"hard_pass": True}}]}}}}


def test_only_provider_facts_cross_boundary():
    case, audit = rebuild_case(source_case())
    assert not audit["blockers"]
    assert "NEVER_IN_PROMPT" not in json.dumps(case)
    assert "hidden_test_facts" not in case
    assert case["pois"][0]["duration_minutes"] == 120
    assert case["restaurants"] == []  # No autogenerated dining catalog.
    assert not audit["training_ready"] and not audit["v9_rollout_ready"]


def test_missing_facts_block_instead_of_defaulting():
    row = source_case()
    poi = row["source"]["snapshot"]["tool_responses"]["search_pois"][0]["data"][0]
    poi.update(location=None, open_time=None, ticket_price=None)
    _, audit = rebuild_case(row)
    assert {"MISSING_POI_COORDINATES", "MISSING_EXPLICIT_OPENING_HOURS", "MISSING_EXPLICIT_POI_COST"} <= set(audit["blockers"])


def test_negative_label_is_not_evidence():
    row = source_case()
    row["source"]["task"]["template_family"] = "verifier-repair:necessary_abort:train"
    _, audit = rebuild_case(row)
    assert "DECISIVE_CONSTRAINT_NOT_RECONSTRUCTED_FROM_PROVIDER_FACTS" in audit["blockers"]


@pytest.mark.asyncio
async def test_fault_recurrence_and_query_result_contract():
    row = source_case()
    rs = row["source"]["snapshot"]["tool_responses"]["search_pois"]
    rs.insert(0, {"error_code": "QUERY_TOO_BROAD", "expected_arguments": {"keywords": ["展馆", "其他"]}, "retryable": True, "fallback_reason": "其他条件过宽"})
    case, _ = rebuild_case(row)
    backend = MigrationResearchExecutor(case)
    for _ in range(2):
        result = await backend._search({"keywords": ["展馆", "其他"]})
        assert result.data is None
    assert (await backend._search({"keywords": ["展馆"]})).data
    assert (await backend._search({"keywords": ["展馆"], "city": "北京"})).data == []


@pytest.mark.asyncio
async def test_timeout_is_bounded_and_no_live_fallback():
    row = source_case()
    row["source"]["snapshot"]["tool_responses"]["search_pois"].insert(0, {"error_code": "UPSTREAM_TIMEOUT", "expected_arguments": {"keywords": ["展馆"]}, "retryable": True})
    case, _ = rebuild_case(row)
    backend = MigrationResearchExecutor(case)
    assert (await backend._search({"keywords": ["展馆"]})).data is None
    assert (await backend._search({"keywords": ["展馆"]})).data
    with pytest.raises(ValueError, match="no grounded provider response"):
        await backend._handlers["search_current_info"]({})
    assert backend._handlers["solve_itinerary"].__func__.__name__ == "_handle_solve_itinerary"


@pytest.mark.asyncio
async def test_observation_contract_and_batch_guard_are_preserved():
    row = source_case()
    row["source"]["snapshot"]["tool_responses"]["search_pois"].insert(0, {"error_code": "UPSTREAM_TIMEOUT", "expected_arguments": {"keywords": ["展馆"]}, "retryable": True})
    case, _ = rebuild_case(row)
    backend = MigrationResearchExecutor(case)
    backend._guard.mode = "enforce"
    calls = [{"id": str(i), "type": "function", "function": {"name": "search_pois", "arguments": json.dumps({"city": "上海", "keywords": ["展馆"] if i == 0 else []})}} for i in range(2)]
    records = await backend.execute(calls, {"max_calls": 1, "grounded_values": {"city": {"上海"}}})
    assert records[0]["observation"]["error"]["code"] == "TOOL_TIMEOUT"
    assert records[0]["observation"]["error"]["retryable"]
    assert not records[1]["guard"]["allowed"]
    assert records[1]["observation"]["error"]["code"] == "CALL_BUDGET_EXCEEDED"
    assert backend.counts["search_pois"] == 1


@pytest.mark.asyncio
async def test_declared_context_tokens_only_are_ignored():
    row = source_case()
    row["source"]["snapshot"]["tool_responses"]["search_pois"].insert(0, {
        "error_code": "QUERY_TOO_BROAD", "expected_arguments": {"keywords": ["展馆", "其他"]},
        "argument_match_mode": "context_tolerant_keywords", "ignored_keyword_values": ["上海"],
        "retryable": True})
    case, _ = rebuild_case(row)
    backend = MigrationResearchExecutor(case)
    assert (await backend._search({"keywords": ["展馆", "上海", "其他"]})).data is None
    assert backend._search_outcomes[-1]["error_code"] == "QUERY_TOO_BROAD"
    await backend._search({"keywords": ["展馆", "其他", "新增条件"]})
    assert backend._search_outcomes[-1] is None
